        private static IEnumerator RunOnBlockTest(string p1Id, string p2Id, bool isAttackerP1, Action<int, int> onComplete)
        {
            LaunchServices.Session.TrySelectMode("LocalVersus", out _);
            LaunchServices.Session.BeginMatch(p1Id, p2Id, "ST07");
            PlayerPrefs.SetString("MDI_GameMode", "LocalVersus");
            PlayerPrefs.SetString("MDI_P1_CharacterId", p1Id);
            PlayerPrefs.SetString("MDI_P2_CharacterId", p2Id);
            PlayerPrefs.SetString("MDI_StageId", "ST07");
            PlayerPrefs.Save();

            SceneManager.LoadScene("BattleArena");
            yield return null;

            float loadTimeout = Time.realtimeSinceStartup + 15f;
            while (Time.realtimeSinceStartup < loadTimeout)
            {
                if (HomegrownCombatDirector.Instance != null && HomegrownCombatDirector.Instance.isActiveAndEnabled
                    && BBMatchSim.Instance != null && BBMatchSim.Instance.p1Brain != null && BBMatchSim.Instance.p2Brain != null
                    && CombatTickEngine.Instance != null && CombatTickEngine.Instance.isActiveAndEnabled
                    && MatchRoundReferee.Instance != null && MatchRoundReferee.Instance.State == MatchState.Fighting)
                {
                    break;
                }
                yield return null;
            }

            var sim = BBMatchSim.Instance;
            Assert.IsNotNull(sim, "BBMatchSim must exist in BattleArena");

            var p1 = sim.p1Brain;
            var p2 = sim.p2Brain;
            Assert.IsNotNull(p1, "p1Brain must exist");
            Assert.IsNotNull(p2, "p2Brain must exist");

            p1.ResetForRound();
            p2.ResetForRound();
            _instance.ClearHeldKeys();
            for (int f = 0; f < 5; f++) yield return null;

            var attacker = isAttackerP1 ? p1 : p2;
            var defender = isAttackerP1 ? p2 : p1;

            Key walkKey = isAttackerP1 ? Key.D : Key.LeftArrow;
            Key blockKey = isAttackerP1 ? Key.RightArrow : Key.A;
            Key attackKey = isAttackerP1 ? Key.J : Key.Numpad1;

            // Defender holds block while attacker walks into 5A range
            float walkTimeout = Time.realtimeSinceStartup + 5.0f;
            while (Mathf.Abs(p1.transform.position.x - p2.transform.position.x) > 0.85f && Time.realtimeSinceStartup < walkTimeout)
            {
                _instance.SetHeldKeys(blockKey, walkKey);
                yield return null;
            }

            _instance.SetHeldKeys(blockKey);
            for (int f = 0; f < 4; f++) yield return null;

            // Attacker presses 5A
            _instance.SetHeldKeys(blockKey, attackKey);
            yield return null;
            yield return null;

            _instance.SetHeldKeys(blockKey);

            // Wait until contact occurs and defender enters Blockstun
            float contactTimeout = Time.realtimeSinceStartup + 3.0f;
            while (defender.bbState != BBState.Blockstun && Time.realtimeSinceStartup < contactTimeout)
            {
                _instance.SetHeldKeys(blockKey);
                yield return null;
            }

            Assert.AreEqual(BBState.Blockstun, defender.bbState, "Defender must enter Blockstun");

            Debug.Log($"<color=#00e676>[ON_BLOCK_CONTACT] tick={CombatTickEngine.Instance.CurrentTick} atkTick={attacker.attackTick} atkState={attacker.bbState} defBStun={defender.blockstunRemaining}</color>");

            int authoredAdvantage = attacker.currentAttack != null ? attacker.currentAttack.advantageOnBlock : 0;

            int attackerRecoverTick = -1;
            int defenderRecoverTick = -1;

            Action<int> onTick = (t) =>
            {
                if (attacker.hitstopRemaining <= 0 && defender.hitstopRemaining <= 0)
                {
                    if (attackerRecoverTick < 0 && (attacker.currentAttack == null || attacker.bbState == BBState.Neutral))
                    {
                        attackerRecoverTick = t;
                        Debug.Log($"<color=#00e676>[ON_BLOCK_ATK_RECOVER] t={t} atkTick={attacker.attackTick} atkState={attacker.bbState} curAtk={(attacker.currentAttack != null ? attacker.currentAttack.moveId : "null")}</color>");
                    }
                    if (defenderRecoverTick < 0 && defender.bbState != BBState.Blockstun && defender.bbState != BBState.BarrierBlockstun)
                    {
                        defenderRecoverTick = t;
                        Debug.Log($"<color=#00e676>[ON_BLOCK_DEF_RECOVER] t={t} defBStun={defender.blockstunRemaining} defState={defender.bbState}</color>");
                    }
                }
            };

            CombatTickEngine.Instance.OnTick += onTick;

            float recoveryTimeout = Time.realtimeSinceStartup + 3.0f;
            while ((attackerRecoverTick < 0 || defenderRecoverTick < 0) && Time.realtimeSinceStartup < recoveryTimeout)
            {
                _instance.SetHeldKeys(blockKey);
                yield return null;
            }

            CombatTickEngine.Instance.OnTick -= onTick;
            _instance.ClearHeldKeys();

            Assert.Greater(attackerRecoverTick, 0, "Attacker must recover to Neutral");
            Assert.Greater(defenderRecoverTick, 0, "Defender must recover from Blockstun");

            int measuredAdvantage = defenderRecoverTick - attackerRecoverTick;
            Debug.Log($"<color=#00e676>[ON_BLOCK_RESULT] atkRec={attackerRecoverTick} defRec={defenderRecoverTick} measured={measuredAdvantage} authored={authoredAdvantage}</color>");
            onComplete?.Invoke(measuredAdvantage, authoredAdvantage);
        }

        public static int MeasurePeakExtensionTick(GameObject prefab, BBAttackData attack)
        {
            if (prefab == null || attack == null || attack.clip == null) return attack.startupFrames;

            GameObject dummy = UnityEngine.Object.Instantiate(prefab);
            dummy.hideFlags = HideFlags.HideAndDontSave;
            int bestTick = attack.startupFrames;
            float maxExt = -999f;

            try
            {
                var anim = dummy.GetComponentInChildren<Animator>();
                if (anim == null) return attack.startupFrames;

                Transform rHand = anim.GetBoneTransform(HumanBodyBones.RightHand);
                Transform lHand = anim.GetBoneTransform(HumanBodyBones.LeftHand);
                Transform rFoot = anim.GetBoneTransform(HumanBodyBones.RightFoot);
                Transform lFoot = anim.GetBoneTransform(HumanBodyBones.LeftFoot);
                Transform[] bones = new Transform[] { rHand, lHand, rFoot, lFoot };

                AnimationClip clip = attack.clip;
                const float EngineFps = 60.0f;
                float t0 = attack.clipFirstFrame > 0 ? attack.clipFirstFrame / EngineFps : 0f;
                float tLast = (attack.clipLastFrame > attack.clipFirstFrame && attack.clipLastFrame > 0) ? attack.clipLastFrame / EngineFps : clip.length;
                tLast = Mathf.Min(tLast, clip.length);
                int impactFrame = attack.measuredImpactFrame > 0 ? attack.measuredImpactFrame : Mathf.RoundToInt(tLast * EngineFps * 0.40f);
                float tImpact = Mathf.Clamp(impactFrame / EngineFps, t0, tLast);

                int tickActive = Mathf.Max(1, attack.startupFrames);
                int tickEnd = Mathf.Max(tickActive + 1, attack.TotalTicks - 1);

                // 1. Identify primary attacking limb: the limb with maximum forward displacement from t0 to tImpact
                clip.SampleAnimation(dummy, t0);
                float[] baseZ = new float[bones.Length];
                for (int b = 0; b < bones.Length; b++)
                {
                    baseZ[b] = (bones[b] != null) ? dummy.transform.InverseTransformPoint(bones[b].position).z : 0f;
                }

                clip.SampleAnimation(dummy, tImpact);
                int primaryBone = -1;
                float maxTravel = 0.04f; // Must travel forward at least 4cm to be considered an attacking limb
                for (int b = 0; b < bones.Length; b++)
                {
                    if (bones[b] == null) continue;
                    float z = dummy.transform.InverseTransformPoint(bones[b].position).z;
                    float travel = z - baseZ[b];
                    if (travel > maxTravel)
                    {
                        maxTravel = travel;
                        primaryBone = b;
                    }
                }

                // If no limb travels forward (e.g. Humanoid clip where SampleAnimation is a no-op, or throw),
                // the piecewise linear time-warp mathematically locks peak limb extension at startupFrames.
                if (primaryBone < 0)
                {
                    return attack.startupFrames;
                }

                // Measure baseline extension at startup (where tImpact is locked)
                clip.SampleAnimation(dummy, tImpact);
                float extAtStartup = dummy.transform.InverseTransformPoint(bones[primaryBone].position).z;

                // Sample ticks from startup - 2 to startup + 2 for the attacking limb
                int startRange = Mathf.Max(0, attack.startupFrames - 2);
                int endRange = Mathf.Min(attack.TotalTicks, attack.startupFrames + 2);

                float peakExt = extAtStartup;
                int peakAtTick = attack.startupFrames;

                for (int t = startRange; t <= endRange; t++)
                {
                    float seekTime;
                    if (t <= tickActive)
                    {
                        seekTime = Mathf.Lerp(t0, tImpact, (float)t / tickActive);
                    }
                    else
                    {
                        seekTime = Mathf.Lerp(tImpact, tLast, (float)(t - tickActive) / (tickEnd - tickActive));
                    }
                    seekTime = Mathf.Clamp(seekTime, t0, tLast);

                    clip.SampleAnimation(dummy, seekTime);

                    float currentExt = dummy.transform.InverseTransformPoint(bones[primaryBone].position).z;
                    // Only choose another tick if it extends significantly further (> 1.5cm) than at startup
                    if (currentExt > peakExt + 0.015f)
                    {
                        peakExt = currentExt;
                        peakAtTick = t;
                    }
                }

                bestTick = peakAtTick;
            }
            finally
            {
                UnityEngine.Object.DestroyImmediate(dummy);
            }

            return bestTick;
        }
    }
