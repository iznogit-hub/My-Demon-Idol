    public class BBFrameDataRunnerComponent : MonoBehaviour
    {
        private static BBFrameDataRunnerComponent _instance;
        private Keyboard _keyboard;
        private readonly List<Key> _heldKeys = new List<Key>();
        private bool _driving = false;

        public const string PrefRunFrameData = "MDI_FrameData_Run";

        [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.AfterSceneLoad)]
        static void CheckAutoStart()
        {
#if UNITY_EDITOR
            if (!UnityEditor.EditorPrefs.GetBool(PrefRunFrameData, false))
                return;

            if (_instance != null) return;

            var go = new GameObject("BBFrameDataRunnerComponent");
            DontDestroyOnLoad(go);
            _instance = go.AddComponent<BBFrameDataRunnerComponent>();
            _instance.StartCoroutine(_instance.RunAutoSuite());
#endif
        }

        void Awake()
        {
            _instance = this;
            _keyboard = Keyboard.current ?? InputSystem.AddDevice<Keyboard>();
        }

        void OnDestroy()
        {
            if (_instance == this) _instance = null;
        }

        void Update()
        {
            if (!_driving) return;
            if (_keyboard == null) _keyboard = Keyboard.current ?? InputSystem.AddDevice<Keyboard>();
            if (_keyboard == null) return;

            var state = _heldKeys.Count > 0 ? new KeyboardState(_heldKeys.ToArray()) : new KeyboardState();
            InputSystem.QueueStateEvent(_keyboard, state);
        }

        public void SetHeldKeys(params Key[] keys)
        {
            _heldKeys.Clear();
            if (keys != null && keys.Length > 0)
            {
                _heldKeys.AddRange(keys);
            }
            _driving = true;
        }

        public void ClearHeldKeys()
        {
            _heldKeys.Clear();
            _driving = true;
        }

        private IEnumerator RunAutoSuite()
        {
            try
            {
                yield return ExecuteAllFrameDataGates();
            }
            finally
            {
#if UNITY_EDITOR
                UnityEditor.EditorPrefs.SetBool(PrefRunFrameData, false);
                UnityEditor.EditorApplication.isPlaying = false;
#endif
            }
        }

